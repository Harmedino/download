// Writes src/environments/environment.ts from the API_BASE_URL environment variable.
// Runs automatically before `npm run build` (e.g. on Vercel/Netlify). Without the variable,
// the committed environment.ts is left untouched.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const url = process.env.API_BASE_URL?.trim();
if (!url) {
  console.log('[set-env] API_BASE_URL not set; using src/environments/environment.ts as committed.');
  process.exit(0);
}
let parsed;
try {
  parsed = new URL(url);
} catch {
  console.error(`[set-env] API_BASE_URL is not a valid URL: ${url}`);
  process.exit(1);
}
if (parsed.protocol !== 'https:' && parsed.hostname !== 'localhost') {
  console.error('[set-env] API_BASE_URL must use https in production.');
  process.exit(1);
}
const target = fileURLToPath(new URL('../src/environments/environment.ts', import.meta.url));
const base = parsed.origin + parsed.pathname.replace(/\/$/, '');
writeFileSync(target, `// Generated by scripts/set-env.mjs at build time.\nexport const environment = {\n  production: true,\n  apiBaseUrl: ${JSON.stringify(base)},\n};\n`);
console.log(`[set-env] apiBaseUrl = ${base}`);
