// Writes src/environments/environment.ts (and public/ads.txt) from environment variables.
// Runs automatically before `npm run build` (e.g. on Vercel/Netlify). Without any of the
// variables below, the committed environment.ts is left untouched.
//
//   API_BASE_URL          https URL of the API
//   ADSENSE_CLIENT        Google AdSense publisher id, e.g. ca-pub-1234567890123456
//   ADSENSE_SLOT_HOME     AdSense ad unit id for the home page
//   ADSENSE_SLOT_RESULT   AdSense ad unit id for the download page
//   ADSENSE_SLOT_FOOTER   AdSense ad unit id for the banner above the footer (every page)
//   ADSTERRA_BANNER_KEY   Adsterra 728x90 banner key (wide screens)
//   ADSTERRA_MOBILE_KEY   Adsterra 320x50 banner key (phones)
//   ADS_TXT               extra lines for /ads.txt, separated by \n or ;
import { readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const env = (name) => process.env[name]?.trim() ?? '';
const fail = (msg) => {
  console.error(`[set-env] ${msg}`);
  process.exit(1);
};
const check = (name, pattern, example) => {
  const value = env(name);
  if (value && !pattern.test(value)) fail(`${name} looks wrong (expected something like ${example}): ${value}`);
  return value;
};

const ads = {
  adsenseClient: check('ADSENSE_CLIENT', /^ca-pub-\d{10,20}$/, 'ca-pub-1234567890123456'),
  adsenseSlots: {
    home: check('ADSENSE_SLOT_HOME', /^\d{5,20}$/, '1234567890'),
    result: check('ADSENSE_SLOT_RESULT', /^\d{5,20}$/, '1234567890'),
    footer: check('ADSENSE_SLOT_FOOTER', /^\d{5,20}$/, '1234567890'),
  },
  adsterraBannerKey: check('ADSTERRA_BANNER_KEY', /^[a-f0-9]{32}$/i, 'a 32-character hex key'),
  adsterraMobileKey: check('ADSTERRA_MOBILE_KEY', /^[a-f0-9]{32}$/i, 'a 32-character hex key'),
};
const extraAdsTxt = env('ADS_TXT')
  .split(/\\n|\n|;/)
  .map((l) => l.trim())
  .filter(Boolean);
const anyAds = [ads.adsenseClient, ads.adsterraBannerKey, ads.adsterraMobileKey].some(Boolean) || extraAdsTxt.length > 0;

const url = env('API_BASE_URL');
if (!url && !anyAds) {
  console.log('[set-env] No API_BASE_URL or ad variables set; using src/environments/environment.ts as committed.');
  process.exit(0);
}

const target = fileURLToPath(new URL('../src/environments/environment.ts', import.meta.url));
let base;
if (url) {
  let parsed;
  try {
    parsed = new URL(url);
  } catch {
    fail(`API_BASE_URL is not a valid URL: ${url}`);
  }
  if (parsed.protocol !== 'https:' && parsed.hostname !== 'localhost') fail('API_BASE_URL must use https in production.');
  base = parsed.origin + parsed.pathname.replace(/\/$/, '');
} else {
  // Keep the API URL that is committed in environment.ts.
  base = readFileSync(target, 'utf8').match(/apiBaseUrl:\s*['"]([^'"]+)['"]/)?.[1];
  if (!base) fail('Could not read apiBaseUrl from environment.ts; set API_BASE_URL.');
}

const environment = { production: true, apiBaseUrl: base, ads };
writeFileSync(target, `// Generated by scripts/set-env.mjs at build time.\nexport const environment = ${JSON.stringify(environment, null, 2)};\n`);
console.log(`[set-env] apiBaseUrl = ${base}`);

// ads.txt tells ad buyers which networks may sell this site's ad space. AdSense needs it to pay out in full.
const adsTxtPath = fileURLToPath(new URL('../public/ads.txt', import.meta.url));
const adsTxt = [...(ads.adsenseClient ? [`google.com, ${ads.adsenseClient.replace(/^ca-/, '')}, DIRECT, f08c47fec0942fa0`] : []), ...extraAdsTxt];
if (adsTxt.length) {
  writeFileSync(adsTxtPath, adsTxt.join('\n') + '\n');
  console.log(`[set-env] wrote public/ads.txt (${adsTxt.length} line${adsTxt.length === 1 ? '' : 's'})`);
} else {
  rmSync(adsTxtPath, { force: true });
}
const enabled = [ads.adsenseClient && 'AdSense', (ads.adsterraBannerKey || ads.adsterraMobileKey) && 'Adsterra'].filter(Boolean);
console.log(`[set-env] ads: ${enabled.length ? enabled.join(' + ') : 'off'}`);
